def _canvas(cv, key, img):
    title, layers = cv["title"], cv["layers"]
    imgs = [f'<img class="ly-base" src="{img}{cv["background"]}" alt="" draggable="false" />']
    for i, ly in enumerate(layers, 1):
        x, y, w, h = ly["box"]
        imgs.append(f'<img class="ly-layer" data-k="{key}{i}" data-mask="{ly["mask"]}" src="{img}{ly["src"]}" '
                    f'alt="{esc(ly["name"])}" draggable="false" '
                    f'style="left:{x}%;top:{y}%;width:{w}%;height:{h}%;z-index:{i + 1}" />')
    imgs.append(f'<img class="ly-orig" src="{img}{cv["original"]}" alt="" draggable="false" />')
    tray = "".join(f'<button type="button" data-k="{key}{i}" title="{esc(ly["name"])}">'
                   f'<img src="{img}{ly["src"]}" alt="{esc(ly["name"])}" /></button>'
                   for i, ly in reversed(list(enumerate(layers, 1))))
    canvas_imgs = "\n".join("                " + t for t in imgs)
    return f'''            <figure class="ly-poster" style="--r: {cv.get("ratio", 1.7778)}; --tray: {cv.get("tray", "#3a3f86")}">
              <figcaption><b>{esc(title)}</b><span>{esc(cv.get("note", f"{len(layers)} layers + background"))}</span></figcaption>
              <div class="ly-stage"><div class="ly-canvas">
{canvas_imgs}
              </div></div>
              <div class="ly-under">
                <button type="button" class="ly-origcard" title="Hold to show the original over the editable image"><img src="{img}{cv["original"]}" alt="Original: {esc(title)}" /><span>Original · hold to compare</span></button>
                <div class="ly-tray">{tray}</div>
              </div>
            </figure>'''



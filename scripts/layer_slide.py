def mask(png, cols=MASK_COLS, alpha_min=24, cover=0.08):
    """'cols,rows,bits' — a cell is 1 when at least `cover` of its pixels have alpha >= alpha_min."""
    from PIL import Image
    a = Image.open(png).convert("RGBA").getchannel("A")
    w, h = a.size
    rows = max(1, round(cols * h / w))
    a = a.point(lambda v: 255 if v >= alpha_min else 0).resize((cols, rows), Image.BOX)
    bits = "".join("1" if v >= 255 * cover else "0" for v in a.tobytes())
    return f"{cols},{rows},{bits}"


def dump(m):
    """The manifest as JSON with one line per layer."""
    def one(o):
        return json.dumps(o, ensure_ascii=False)
    cvs = []
    for cv in m["canvases"]:
        head = {k: v for k, v in cv.items() if k != "layers"}
        rows = ",\n".join("     " + one(ly) for ly in cv["layers"])
        cvs.append("  " + one(head)[:-1] + ', "layers": [\n' + rows + "\n  ]}")
    return '{"canvases": [\n' + ",\n".join(cvs) + "\n]}\n"


def fill_masks(manifest_path):
    p = Path(manifest_path)
    base = p.parent
    m = json.loads(p.read_text(encoding="utf-8"))
    for cv in m["canvases"]:
        for ly in cv["layers"]:
            ly["mask"] = mask(base / ly["src"])
    p.write_text(dump(m), encoding="utf-8")
    print("ok", p, sum(len(cv["layers"]) for cv in m["canvases"]), "masks")


CSS_START, CSS_END = "      /* ── Layer playground (.ly-wrap)", "      .ly-hint b {"
JS_START, JS_END = "    <script>\n      /* Layer playground (.ly-wrap)", "      })();\n    </script>\n"


def sync(path):
    """Put the current LAYER_CSS / LAYER_JS into an HTML file: replace the blocks if present, otherwise add
    the CSS before the last </style> and the script before </body>."""
    p = Path(path)
    s = p.read_text(encoding="utf-8")
    if CSS_START in s:
        a = s.index(CSS_START)
        b = s.index("\n", s.index(CSS_END, a)) + 1
        s = s[:a].rstrip(" ").rstrip("\n") + "\n" + LAYER_CSS.lstrip("\n") + s[b:]
    else:
        i = s.rindex("    </style>")
        s = s[:i] + LAYER_CSS.lstrip("\n") + s[i:]
    if JS_START in s:
        a = s.index(JS_START)
        b = s.index(JS_END, a) + len(JS_END)
        s = s[:a] + LAYER_JS.lstrip("\n") + s[b:]
    else:
        i = s.rindex("  </body>")
        s = s[:i] + LAYER_JS.lstrip("\n") + s[i:]
    p.write_text(s, encoding="utf-8")
    print("ok", p)



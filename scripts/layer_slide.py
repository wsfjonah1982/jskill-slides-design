"""Layer playground slide for the BytePlus decks (slides-design skill).

One or two images, each shown as a clean background plus its cut-out objects (transparent PNG layers).
In the browser the audience can drag any object, resize it from a corner, rotate it from the top handle
(Shift snaps to 15 degrees), drop it on the other image, hide the backgrounds, hold to compare with the
original image, and reset. Clicks only hit an object's visible pixels: every layer carries a small
alpha mask (40 columns wide) computed from its PNG.

Pieces:
    LAYER_CSS / LAYER_JS     the styles and the runtime (already inside templates/byteplus*/template.html)
    layer_wrap(manifest)     the slide content (a .ly-wrap block) for one manifest; layer_wrap(None) = the
                             placeholder layout the templates ship with (no sample images)
    python scripts/layer_slide.py masks <manifest.json>
                             (re)compute every layer's "mask" from its PNG (needs Pillow)
    python scripts/layer_slide.py sync <deck.html>
                             put the current LAYER_CSS / LAYER_JS into a deck or template (replace or add)

Manifest (layers.json; image paths are relative to the manifest's own folder):
{
  "canvases": [
    {"title": "SUMMER FIZZ", "note": "13 layers + background", "ratio": 1.7778, "tray": "#3f9f95",
     "background": "fizz/background.jpg", "original": "fizz/original.jpg",
     "layers": [                                   # bottom → top
       {"src": "fizz/l01.png", "name": "Title", "box": [x, y, w, h], "mask": "40,5,0110…"}
     ]}
  ]
}
box = left, top, width, height of the layer in % of the canvas. "tray" = the thumbnail tile colour (pick one
that the cut-outs read well on). Two canvases at most.
"""
